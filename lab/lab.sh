#!/usr/bin/env bash
# Manage the local lab VMs.
#   lab/lab.sh use ring|enterprise    select the topology (writes inventory.yaml for netmedic)
#   lab/lab.sh up|down|ps|status      start / stop / list / BGP+OSPF state
#   lab/lab.sh ssh <router> [cmd]
set -euo pipefail

LAB_DIR="$(cd "$(dirname "$0")" && pwd)"
STATE="$LAB_DIR/state"
KEY="$STATE/id_ed25519"
export LAB_STATE="$STATE"
mkdir -p "$STATE"

TOPO="${LAB_TOPO:-$(cat "$STATE/topology" 2>/dev/null || echo ring)}"
META="$STATE/topology-$TOPO.json"

meta() {
  [[ -f $META && $META -nt $LAB_DIR/flake.nix ]] || nix eval --json "$LAB_DIR#topologies.$TOPO" >"$META"
  cat "$META"
}
routers() { meta | python3 -c 'import json,sys; r=json.load(sys.stdin)["routers"]; print(" ".join(sorted(r, key=lambda n: r[n]["id"])))'; }
port() { meta | python3 -c 'import json,sys; print(2220 + json.load(sys.stdin)["routers"][sys.argv[1]]["id"])' "$1"; }

# QEMU runs in its own session (the NixOS run script detaches it): find VMs by process name.
vm_pid() { pgrep -f "qemu-system.*-name $1( |\$)" | head -1 || true; }

ssh_r() {
  local r=$1; shift
  timeout "${LAB_SSH_TIMEOUT:-8}" ssh -i "$KEY" -p "$(port "$r")" -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null \
    -o LogLevel=ERROR -o ConnectTimeout=3 root@127.0.0.1 "$@"
}

inventory() {
  # netmedic manages only the routers marked managed (the ISPs are external).
  meta | python3 -c '
import json, sys
d = json.load(sys.stdin)
print("# Generated by lab/lab.sh use <topology>. Do not edit.")
print("ssh:\n  user: root\n  key: lab/state/id_ed25519")
print("targets: " + json.dumps(d.get("targets", [])))
print("notes: |")
for line in d["notes"].strip().splitlines():
    print("  " + line)
print("routers:")
for n, r in sorted(d["routers"].items(), key=lambda kv: kv[1]["id"]):
    if not r.get("managed", True):
        continue
    extra = "".join(f", {k}: {r[k]}" for k in ("role", "layer") if r.get(k) is not None)
    i, asn = r["id"], r["asn"]
    print(f"  {n}: {{ host: 127.0.0.1, port: {2220 + i}, asn: {asn}, loopback: 10.0.255.{i}{extra} }}")
' >"${LAB_INVENTORY:-$LAB_DIR/../inventory.yaml}"
}

use() {
  local new=$1
  [[ $new == ring || $new == enterprise ]] || { echo "unknown topology: $new (ring|enterprise)"; exit 1; }
  echo "$new" >"$STATE/topology"
  TOPO=$new; META="$STATE/topology-$TOPO.json"
  inventory
  echo "topology: $TOPO ($(routers)) — inventory.yaml updated"
}

up() {
  [[ -f $KEY ]] || ssh-keygen -q -t ed25519 -N "" -C netmedic-lab -f "$KEY"
  cp "$KEY.pub" "$STATE/authorized_keys"
  inventory
  local r
  for r in $(routers); do
    if [[ -n $(vm_pid "$r") ]]; then
      echo "$r already running"; continue
    fi
    nix build "$LAB_DIR#vm-$r" -o "$STATE/vm-$r"
    mkdir -p "$STATE/$r"
    # Redirect the whole subshell, or it keeps our stdout open for the VM's lifetime.
    (cd "$STATE/$r" && TMPDIR="$STATE/$r" exec setsid "$STATE/vm-$r/bin/run-$r-vm") \
      </dev/null >"$STATE/$r.log" 2>&1 &
    echo "$r started (ssh port $(port "$r"), log $STATE/$r.log)"
  done
  echo "waiting for SSH..."
  for r in $(routers); do
    for _ in $(seq 60); do ssh_r "$r" true 2>/dev/null && break; sleep 2; done
    ssh_r "$r" true && echo "$r ready"
  done
}

down() {
  # Stops the VMs of the current topology.
  local r pid
  for r in $(routers); do
    pid=$(vm_pid "$r")
    [[ -n $pid ]] && kill "$pid" && echo "$r stopped"
  done
  for _ in $(seq 20); do
    any=""
    for r in $(routers); do [[ -n $(vm_pid "$r") ]] && any=1; done
    [[ -z $any ]] && break
    sleep 0.5
  done
}

ps_vms() {
  echo "topology: $TOPO"
  local r pid
  for r in $(routers); do
    pid=$(vm_pid "$r")
    if [[ -n $pid ]]; then
      echo "$r  running  pid $pid  ssh 127.0.0.1:$(port "$r")"
    else
      echo "$r  stopped"
    fi
  done
}

status() {
  local r
  for r in $(routers); do
    echo "=== $r"
    ssh_r "$r" 'birdc show protocols | grep -E "BGP|OSPF"; birdc show ospf neighbors 2>/dev/null | tail -n +3 || true' 2>/dev/null \
      || echo "(unreachable)"
  done
}

case "${1:-}" in
  use) use "${2:-}" ;;
  up) up ;;
  down) down ;;
  ps) ps_vms ;;
  status) status ;;
  inventory) inventory ;;
  routers) routers ;;
  ssh) shift; ssh_r "$@" ;;
  *) echo "usage: $0 use ring|enterprise | up | down | ps | status | ssh <router> [cmd]"; exit 1 ;;
esac
